#include "glyphs.hpp"
#include <stdint.h>

struct IwSpan {
    uint16_t code;
    uint32_t offset;
    uint8_t n;
};

static IwGlyph find_span(const IwSpan *spans, int count, const uint32_t *data, unsigned code) {
    int lo = 0, hi = count;
    while (lo < hi) {
        int mid = (lo + hi) >> 1;
        if (spans[mid].code < code) lo = mid + 1;
        else hi = mid;
    }
    if (lo < count && spans[lo].code == code) {
        IwGlyph g;
        g.cols = data + spans[lo].offset;
        g.n = spans[lo].n;
        return g;
    }
    IwGlyph g;
    g.cols = 0;
    g.n = 0;
    return g;
}


